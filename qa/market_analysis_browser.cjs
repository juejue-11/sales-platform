const path = require('node:path');
const { chromium } = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
(async () => {
  const [url, output] = process.argv.slice(2);
  const browser = await chromium.launch({headless:true, channel:'msedge'});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];
    page.on('pageerror', error => errors.push(error.message));
    const checkWidth = async () => {
      const size = await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
      if(size.scroll>size.width+2) throw Error('Page overflow: '+JSON.stringify(size));
    };
    await page.goto(url+'/settings');
    await page.getByText('默认分析目标：矿山设备市场开发',{exact:true}).waitFor();
    await page.getByText('未提供，可继续分析',{exact:true}).waitFor();
    if((await page.locator('body').innerText()).includes('market_default_v1')) throw Error('Implementation version exposed');
    await page.screenshot({path:path.join(output,'settings-desktop.png'),fullPage:true});
    await page.goto(url+'/projects/9101');
    await page.getByRole('heading',{name:'空资料市场分析验收',exact:true}).waitFor();
    await page.getByText('有条件关注',{exact:true}).first().waitFor();
    await page.getByText('企业匹配：未评估',{exact:true}).first().waitFor();
    await page.getByRole('radio').first().check();
    await page.locator('#decision-owner').fill('浏览器验收负责人');
    await page.locator('#decision-next-action').fill('取得技术清单后核实参与条件');
    await page.getByRole('button',{name:'保存人工决定'}).click();
    await page.getByText('人工决定已保存，历史记录已保留',{exact:true}).waitFor();
    const saved = (await (await page.request.get(url+'/api/projects/9101')).json()).decision;
    if(saved.selected_option_id!=='verify'||saved.owner!=='浏览器验收负责人') throw Error('General action selection not persisted');
    await page.reload();
    await page.getByRole('radio').first().waitFor();
    if(!await page.getByRole('radio').first().isChecked()) throw Error('Current action selection lost');
    await page.screenshot({path:path.join(output,'project-desktop.png'),fullPage:true});
    await page.goto(url+'/projects/9102');
    await page.getByRole('heading',{name:'旧判断兼容验收',exact:true}).waitFor();
    await page.getByText('旧语义',{exact:true}).first().waitFor();
    if(await page.getByRole('radio').count()) throw Error('Legacy options selectable');
    if(await page.locator('#decision-owner').inputValue()!=='历史负责人') throw Error('Historical human decision missing');
    await page.screenshot({path:path.join(output,'legacy-desktop.png'),fullPage:true});
    await page.goto(url+'/');
    await page.locator('[data-testid="opportunity-item"][href="/projects/9101"]').waitFor();
    const card = page.locator('[data-testid="opportunity-item"][href="/projects/9101"]');
    if(!(await card.innerText()).includes('有条件关注')) throw Error('Market label missing from opportunity card');
    await page.setViewportSize({width:390,height:844});
    await checkWidth();
    await page.screenshot({path:path.join(output,'home-mobile.png'),fullPage:true});
    await page.goto(url+'/projects/9101');
    await page.getByRole('heading',{name:'空资料市场分析验收',exact:true}).waitFor();
    await checkWidth();
    await page.screenshot({path:path.join(output,'project-mobile.png'),fullPage:true});
    await page.goto(url+'/settings');
    await page.getByText('未提供，可继续分析',{exact:true}).waitFor();
    await checkWidth();
    await page.locator('#business-company-name').fill('仅名称验收公司');
    await page.locator('#business-regions').fill('山西');
    await page.locator('#rule-target-keywords').fill('破碎机\n备件');
    await page.getByText('未提供，可继续分析',{exact:true}).waitFor();
    await page.getByRole('button',{name:/保存配置/}).click();
    await page.getByText('业务配置已保存，相关旧判断会按后端规则标记待复核',{exact:true}).waitFor();
    const settings=(await(await page.request.get(url+'/api/settings')).json());
    if(settings.analysis.company_profile_present||settings.business.target_keywords.join('|')!=='破碎机|备件') throw Error('Identity/preferences treated as capability');
    await page.screenshot({path:path.join(output,'settings-mobile.png'),fullPage:true});
    if(errors.length) throw Error(errors.join('\n'));
    console.log(JSON.stringify({browser:'passed',desktop:1440,mobile:390,runtimeErrors:errors}));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
