const path = require('node:path');
const { chromium } = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
(async () => {
  const url=process.argv[2], output=process.argv[3];
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url+'/projects/9001');
    await page.getByRole('heading',{name:'验收项目：破碎机备件采购',exact:true}).waitFor();
    const field=(label,tag='input')=>page.locator('.ant-form-item').filter({has:page.locator('label').filter({hasText:new RegExp('^'+label+'$')})}).locator(tag);
    await field('负责人').fill('浏览器验收负责人');
    await page.waitForTimeout(1200);
    if(await field('负责人').inputValue()!=='浏览器验收负责人')throw new Error('First edit was overwritten');
    await field('下一步').fill('通过浏览器确认技术清单');
    await field('备注','textarea').fill('仅用于隔离验收');
    await page.getByRole('radio').nth(1).check();
    await page.getByRole('radio').first().check();
    if (!await page.getByRole('radio').first().isChecked() || await page.getByRole('radio').nth(1).isChecked()) throw new Error('Option inputs overlap or do not switch correctly');
    await page.getByRole('button',{name:'保存人工决定'}).click();
    await page.getByText('人工决定已保存，历史记录已保留',{exact:true}).waitFor();
    const decision=await page.request.get(url+'/api/projects/9001');
    const saved=(await decision.json()).decision;
    if(saved.owner!=='浏览器验收负责人'||saved.next_action!=='通过浏览器确认技术清单'||!saved.selected_option_id)throw new Error('Browser decision was not persisted');
    await page.screenshot({path:path.join(output,'project-desktop.png'),fullPage:true});
    await page.goto(url+'/settings');
    await page.getByRole('button',{name:'保存配置',exact:true}).waitFor();
    const keywords=field('目标关键词','textarea');
    await keywords.fill('');
    await keywords.pressSequentially('破碎机');
    await keywords.press('Enter');
    await keywords.pressSequentially('备件');
    if(await keywords.inputValue()!=='破碎机\n备件')throw new Error('Keyword newline was stripped');
    await field('公司名称').fill('浏览器验收公司');
    await page.getByRole('button',{name:'保存配置',exact:true}).click();
    await page.getByText('业务配置已保存，相关旧判断会按后端规则标记待复核',{exact:true}).waitFor();
    const settings=(await (await page.request.get(url+'/api/settings')).json());
    if(settings.business.target_keywords.join('|')!=='破碎机|备件'||!settings.ai.has_api_key)throw new Error('Settings save mismatch or key not retained');
    await page.goto(url+'/operations');
    await page.getByRole('button',{name:'立即导入 records.jsonl',exact:true}).waitFor();
    await page.goto(url+'/');
    await page.getByText('验收项目：破碎机备件采购',{exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'home-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'home-mobile.png'),fullPage:true});
    const mobile=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:window.innerWidth}));
    if(mobile.scroll>mobile.width+2)throw new Error('Mobile page overflow '+JSON.stringify(mobile));
    if(errors.length)throw new Error('Runtime errors: '+errors.join('\n'));
    console.log(JSON.stringify({browser:'passed',mobile,runtimeErrors:errors}));
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
